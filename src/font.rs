const DEGREE: [u8; 5] = [0x00, 0x06, 0x09, 0x09, 0x06];
const UNKNOWN: [u8; 5] = [0x7F, 0x41, 0x41, 0x41, 0x7F];

/// Acentos desenhados nas duas linhas de cima (livres nas minúsculas).
const ACUTE: [u8; 5] = [0x00, 0x00, 0x02, 0x01, 0x00];
const GRAVE: [u8; 5] = [0x00, 0x01, 0x02, 0x00, 0x00];
const CIRCUMFLEX: [u8; 5] = [0x00, 0x02, 0x01, 0x02, 0x00];
const TILDE: [u8; 5] = [0x00, 0x02, 0x01, 0x02, 0x01];

fn ascii(c: char) -> [u8; 5] {
    let i = c as usize;
    if (32..127).contains(&i) { ASCII[i - 32] } else { UNKNOWN }
}

fn overlay(base: char, accent: [u8; 5]) -> [u8; 5] {
    let mut g = ascii(base);
    // Nas maiúsculas não há espaço acima: mostramos só a letra.
    if base.is_ascii_lowercase() {
        for (col, a) in g.iter_mut().zip(accent) {
            *col |= a;
        }
    }
    g
}

pub fn glyph(c: char) -> [u8; 5] {
    match c {
        '°' | 'º' => DEGREE,
        'á' | 'é' | 'í' | 'ó' | 'ú' | 'Á' | 'É' | 'Í' | 'Ó' | 'Ú' => overlay(strip(c), ACUTE),
        'à' | 'À' => overlay(strip(c), GRAVE),
        'â' | 'ê' | 'ô' | 'Â' | 'Ê' | 'Ô' => overlay(strip(c), CIRCUMFLEX),
        'ã' | 'õ' | 'ñ' | 'Ã' | 'Õ' | 'Ñ' => overlay(strip(c), TILDE),
        _ => {
            let s = strip(c);
            ascii(s)
        }
    }
}

fn strip(c: char) -> char {
    match c {
        'á' | 'à' | 'â' | 'ã' | 'ä' => 'a',
        'Á' | 'À' | 'Â' | 'Ã' | 'Ä' => 'A',
        'é' | 'è' | 'ê' | 'ë' => 'e',
        'É' | 'È' | 'Ê' | 'Ë' => 'E',
        'í' | 'ì' | 'î' | 'ï' => 'i',
        'Í' | 'Ì' | 'Î' | 'Ï' => 'I',
        'ó' | 'ò' | 'ô' | 'õ' | 'ö' => 'o',
        'Ó' | 'Ò' | 'Ô' | 'Õ' | 'Ö' => 'O',
        'ú' | 'ù' | 'û' | 'ü' => 'u',
        'Ú' | 'Ù' | 'Û' | 'Ü' => 'U',
        'ç' => 'c',
        'Ç' => 'C',
        'ñ' => 'n',
        'Ñ' => 'N',
        _ => c,
    }
}

/// Converte um texto em colunas de pixels (largura proporcional, 1 coluna de espaço entre letras).
pub fn text_columns(text: &str) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len() * 6);
    for c in text.chars() {
        if c == ' ' {
            out.extend_from_slice(&[0, 0, 0]);
            continue;
        }
        let g = glyph(c);
        let first = g.iter().position(|&b| b != 0).unwrap_or(0);
        let last = g.iter().rposition(|&b| b != 0).unwrap_or(4);
        out.extend_from_slice(&g[first..=last]);
        out.push(0);
    }
    if out.last() == Some(&0) {
        out.pop();
    }
    out
}
